defmodule ExPtp.RTL.Servo do
  @moduledoc """
  The PTP servo in hardware: PI controller, lock detector and conversion of
  the frequency correction into the wallclock's per-tick increment, so the
  loop from offset sample to rate change runs without software.

  ## PI: the scan kernel through `ExHdl.RTL.Wrap.scan/1`

  `ExPtp.Servo.pi_step/5` is generated by `ExHdl.DSP.scan_to_sv/3` (`ii: 2`,
  latency 11 cycles, the multiply sits in the feedback loop) and wrapped as
  a black box: the generated SystemVerilog is exactly what the Nx kernel
  describes, so there is one source for the CPU reference (`Servo.run/4`),
  the bit-identical integer model (`ExPtp.Servo.FixedPI`) and the hardware.
  A hand written RTL version would duplicate the arithmetic and could drift.
  The cost: wrapped kernels have no BEAM simulator model, so this module is
  verified in Verilator directly against `FixedPI`, `ExPtp.Servo.Lock` and
  `inc_for/2` (`test/rtl/servo_test.exs`), not BEAM against Verilator.

  ## Ports (domain `:sys`)

  | Port | Meaning |
  |---|---|
  | `err_valid`, `err` (s32) | offset from master in ns with 8 fractional bits (`FixedPI.err/1`); a sample arriving while the previous one is still in the kernel is dropped (`dropped` pulses) |
  | `load`, `kp`, `ki` (s24, 20 fractional bits) | `load` captures the gains; they apply between samples |
  | `nominal` (u40), `scale` (u48) | wallclock nominal increment and `scale/1` of it |
  | `thr`, `thr_unlock` (u32, raw error), `needed` (u8) | lock detector, as `ExPtp.Servo.Lock` (`thr_unlock` = unlock factor times `thr`) |
  | `ppb_valid`, `ppb` (s28) | the PI output, 8 fractional bits (`FixedPI.ppb/1`) |
  | `inc_wr`, `inc` (u40) | strobe and value for `ExPtp.RTL.Wallclock`'s `inc_wr` / `inc_in`, two cycles after `ppb_valid` |
  | `locked` | lock state, updated with each accepted sample |
  | `range_err` | the kernel output did not fit 28 bits (never; a check) |

  The integrator state is reset by the module reset only.

  ## Rate conversion

  `inc = nominal + ((ppb * scale + 2^39) >> 40)` (arithmetic shift). With
  `scale = round(nominal * 2^40 / (256 * 10^9))` this is
  `ExPtp.Wallclock.increment/2` for `ppb / 256` near one unit of 2^-32 ns
  (`inc_for/2`).
  """
  use ExHdl.RTL
  import Bitwise

  alias ExHdl.RTL.Wrap
  alias ExPtp.Servo, as: S
  alias NxFixed.Num

  @doc "`scale` input for a wallclock nominal increment."
  def scale(nominal), do: div(nominal * (1 <<< 40) + 128 * 1_000_000_000, 256 * 1_000_000_000)

  @doc "Increment for a raw servo output (ppb with 8 fractional bits): the hardware's arithmetic."
  def inc_for(raw_ppb, nominal), do: nominal + ((raw_ppb * scale(nominal) + (1 <<< 39)) >>> 40)

  @doc "The wrapped PI kernel (`ExHdl.Backends.SystemVerilog.Scan.Design`)."
  def design do
    t = &Nx.Defn.Composite.traverse(&1, fn x -> Nx.to_template(x) end)

    args = [
      t.(Num.constant(1.0, S.err_format())),
      t.(Num.zeros({}, S.fixed_format())),
      t.(Num.constant(0.7, S.gain_format())),
      t.(Num.constant(0.3, S.gain_format())),
      [format: S.fixed_format()]
    ]

    {:ok, d} =
      ExHdl.DSP.scan_to_sv(&S.pi_step/5, args,
        state: 1,
        ii: 2,
        name: "ptp_servo_pi",
        param_names: ["kp", "ki"]
      )

    d
  end

  def build do
    module "ptp_servo" do
      err_valid = input(:err_valid, 1)
      err = input(:err, s(32))
      load = input(:load, 1)
      kp = input(:kp, s(24))
      ki = input(:ki, s(24))
      nominal = input(:nominal, 40)
      scale = input(:scale, 48)
      thr = input(:thr, 32)
      thr_unlock = input(:thr_unlock, 32)
      needed = input(:needed, 8)

      inc_wr = output(:inc_wr, 1, reset: 0)
      inc = output(:inc, 40, reset: 0)
      ppb_valid = output(:ppb_valid, 1)
      ppb = output(:ppb, s(28), reset: 0)
      locked = output(:locked, 1, reset: 0)
      dropped = output(:dropped, 1, reset: 0)
      range_err = output(:range_err, 1)

      k =
        instance(:k, Wrap.scan(design()),
          connect: [
            p_kp: as_unsigned(sext(kp, 32)),
            p_ki: as_unsigned(sext(ki, 32)),
            p_load: load
          ]
        )

      pend = reg(:pend, 1)
      pend_err = reg(:pend_err, s(32), reset: nil)
      v1 = reg(:v1, 1)
      v2 = reg(:v2, 1)
      prod = reg(:prod, s(78), reset: nil)
      run = reg(:run, 8)
      kv = wire(:kv, k.m_axis.tvalid)

      k.s_axis.tdata <~ as_unsigned(pend_err)
      k.s_axis.tvalid <~ pend
      k.m_axis.tready <~ 1
      ppb_valid <~ v1
      # the kernel output is s32 holding an s28 value: the top bits must repeat bit 27
      top = k.m_axis.tdata[27..31]
      range_err <~ (reduce_or(top) and not reduce_and(top))

      # 0 - err instead of -err: Yosys rejects the SV emitted for unary minus on a cast
      neg = sub_wrap(const(0, s(33)), sext(err, 33))
      mag = wire(:mag, mux(err < 0, as_unsigned(neg), as_unsigned(err[0..30]) |> zext(33)))
      near = wire(:near, mag <= thr)
      far = wire(:far, mag > thr_unlock)
      run1 = wire(:run1, mux(run == 255, run, add_wrap(run, 1)))

      sync do
        dropped <~ (err_valid and pend)
        if err_valid and not pend, do: pend_err <~ err
        if err_valid and not pend, do: pend <~ 1
        if pend and k.s_axis.tready, do: pend <~ 0

        # lock detector on every accepted sample
        if err_valid and not pend do
          if near do
            run <~ run1
            if run1 >= needed, do: locked <~ 1
          else
            run <~ 0
            if far, do: locked <~ 0
          end
        end

        # PI output, then the rate conversion in two registered steps
        v1 <~ kv
        v2 <~ v1
        inc_wr <~ v2
        if kv, do: ppb <~ as_signed(trunc(k.m_axis.tdata, 28))
        if v1, do: prod <~ (ppb * to_signed(scale))

        if v2,
          do:
            inc
            <~ trunc(as_unsigned(to_signed(nominal) + trunc((prod + (1 <<< 39)) >>> 40, 41)), 40)
      end
    end
  end
end
